"""Build the extension's icons from the SVG logos in assets/.

  assets/logo.svg        full logo (shield on a fishing line) -> 48px and 128px icons + panel header
  assets/logo-small.svg  shield-only version that stays readable -> 16px and 32px icons

PNGs are rendered with headless Google Chrome at 512px, then downscaled with macOS `sips`
for clean anti-aliasing. The panel can't load image files inside Gmail (page CSP), so the
full logo is also converted to extension/logo.js, which panel.js builds with DOM calls.

Usage: python3 tools/build_icons.py              # all sizes
       python3 tools/build_icons.py 48 128       # only these sizes (the panel logo is rebuilt
                                                 # whenever 48 or 128 is included)
"""

import json
import shutil
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets"
ICONS = ROOT / "extension" / "icons"
CHROME = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"
RENDER_SIZE = 512
SIZES = {16: "logo-small.svg", 32: "logo-small.svg", 48: "logo.svg", 128: "logo.svg"}
SVG_NS = "{http://www.w3.org/2000/svg}"


def render_png(svg: Path, out: Path) -> None:
    with tempfile.TemporaryDirectory() as tmp:
        page = Path(tmp) / "page.html"
        page.write_text(
            "<!doctype html><style>html,body{margin:0;background:transparent}img{display:block}</style>"
            f'<img src="{svg.as_uri()}" width="{RENDER_SIZE}" height="{RENDER_SIZE}">'
        )
        shot = Path(tmp) / "shot.png"
        subprocess.run(
            [
                CHROME, "--headless=new", "--disable-gpu", "--hide-scrollbars",
                "--default-background-color=00000000", "--force-device-scale-factor=1",
                f"--window-size={RENDER_SIZE},{RENDER_SIZE}", f"--screenshot={shot}", page.as_uri(),
            ],
            check=True, capture_output=True,
        )
        shutil.copy(shot, out)


def svg_to_tree(node: ET.Element) -> list:
    """[tag, {attrs}, [children]] with namespaces stripped, for panel.js to rebuild."""
    tag = node.tag.replace(SVG_NS, "")
    return [tag, dict(node.attrib), [svg_to_tree(child) for child in node]]


def write_logo_js(svg: Path) -> None:
    root = ET.parse(svg).getroot()
    attrs = {k: v for k, v in root.attrib.items() if k in ("viewBox", "fill")}
    data = {"attrs": attrs, "children": [svg_to_tree(child) for child in root]}
    (ROOT / "extension" / "logo.js").write_text(
        "// Generated by tools/build_icons.py from assets/logo.svg. Do not edit by hand.\n"
        f"self.PhishGuardLogo = {json.dumps(data, separators=(',', ':'))};\n"
    )


def main() -> None:
    if not Path(CHROME).exists():
        sys.exit(f"Google Chrome not found at {CHROME}")
    sizes = [int(a) for a in sys.argv[1:]] or list(SIZES)
    unknown = set(sizes) - set(SIZES)
    if unknown:
        sys.exit(f"Unknown size(s) {sorted(unknown)}; choose from {list(SIZES)}")
    with tempfile.TemporaryDirectory() as tmp:
        for name in sorted({SIZES[s] for s in sizes}):
            render_png(ASSETS / name, Path(tmp) / f"{name}.png")
        for size in sizes:
            name = SIZES[size]
            out = ICONS / f"icon{size}.png"
            shutil.copy(Path(tmp) / f"{name}.png", out)
            subprocess.run(["sips", "-z", str(size), str(size), str(out)], check=True, capture_output=True)
            print(f"wrote {out.relative_to(ROOT)} from {name}")
    if "logo.svg" in {SIZES[s] for s in sizes}:
        write_logo_js(ASSETS / "logo.svg")
        print("wrote extension/logo.js")


if __name__ == "__main__":
    main()
